"use client";

import { useState, type FormEvent } from "react";
import { useRouter } from "next/navigation";
import { Hexagon, Lock } from "lucide-react";

export default function LoginPage() {
  const router = useRouter();
  const [password, setPassword] = useState("");
  const [error, setError] = useState("");
  const [busy, setBusy] = useState(false);

  async function submit(e: FormEvent) {
    e.preventDefault();
    setBusy(true);
    setError("");
    try {
      const res = await fetch("/api/lm-auth/login", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ password }),
      });
      if (res.ok) {
        router.push("/");
        router.refresh();
        return;
      }
      const body = await res.json().catch(() => ({}));
      setError(body?.error || `Sign-in failed (${res.status})`);
    } finally {
      setBusy(false);
    }
  }

  return (
    <div className="flex min-h-screen items-center justify-center px-4">
      <div className="panel w-full max-w-[340px] px-7 py-8">
        <div className="flex items-center gap-2.5">
          <Hexagon size={20} strokeWidth={1.8} className="text-[var(--color-accent)]" />
          <div>
            <div className="text-[14px] font-semibold tracking-tight">LocalMesh</div>
            <div className="text-[10px] text-[var(--color-text-faint)]">private AI cluster</div>
          </div>
        </div>

        <div className="mt-7">
          <div className="label">Dashboard password</div>
          <form onSubmit={submit} className="mt-2.5 flex flex-col gap-3">
            <div className="relative">
              <Lock
                size={13}
                className="absolute left-3 top-1/2 -translate-y-1/2 text-[var(--color-text-faint)]"
              />
              <input
                type="password"
                autoFocus
                autoComplete="current-password"
                value={password}
                onChange={(e) => setPassword(e.target.value)}
                placeholder="••••••••••••"
                className="w-full rounded-md border bg-transparent py-2 pl-9 pr-3 text-[13px] outline-none transition-colors focus:border-[var(--color-accent)]"
                style={{ borderColor: "var(--color-border)" }}
              />
            </div>
            {error && <div className="text-[12px] text-[var(--color-danger)]">{error}</div>}
            <button
              type="submit"
              disabled={busy || !password}
              className="rounded-md bg-[var(--color-accent)] py-2 text-[13px] font-medium text-black transition-opacity hover:opacity-90 disabled:opacity-40"
            >
              {busy ? "Signing in…" : "Sign in"}
            </button>
          </form>
          <p className="mt-5 text-[11px] leading-relaxed text-[var(--color-text-faint)]">
            First boot? The password is generated by the server at{" "}
            <code className="mono">bootstrap-dashboard.password</code> in its data
            directory, or set{" "}
            <code className="mono">LOCALMESH_DASHBOARD_PASSWORD</code>.
          </p>
        </div>
      </div>
    </div>
  );
}
